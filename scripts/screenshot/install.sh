#!/bin/sh
# Installs the screenshot tool (#510) for interactive sessions:
#
#   scripts/screenshot/install.sh DEST [REF]     (make screenshot-install)
#
# The launcher DEST/bin/komki-screenshot runs outside every sandbox, so
# nothing it starts may come from a place a session can write. The source
# comes from GitHub, not from the local repository: sessions may write .git
# (refs, objects, config). The Elixir and Erlang runtimes come from the
# .tool-versions of that same commit, as asdf install paths, without running
# any interpreter: the asdf shims would pick a version, or a `path:`, from
# the .tool-versions of the current directory.
set -eu

repo=croesnick/kommunalpolitik_ki
dest=$1
ref=${2:-main}
installs=$(realpath "$HOME/.asdf/installs")

sha=$(gh api "repos/$repo/commits/$ref" --jq .sha)
case "$sha" in
  "" | *[!0-9a-f]*) echo "Kein Commit für $ref: $sha" >&2; exit 1 ;;
esac

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
gh api "repos/$repo/tarball/$sha" > "$tmp/src.tar.gz"
mkdir "$tmp/src"
tar -xzf "$tmp/src.tar.gz" -C "$tmp/src" --strip-components=1

# A plain version only (no path:, ref: or system), resolved below the asdf
# installs, which the sandbox does not write.
runtime() {
  version=$(awk -v tool="$1" '$1 == tool { print $2 }' "$tmp/src/.tool-versions")
  case "$version" in
    "" | *[!0-9A-Za-z.-]*)
      echo "$1: keine feste Version in .tool-versions von $sha: '$version'" >&2; exit 1 ;;
  esac
  dir=$(realpath "$installs/$1/$version") \
    || { echo "$1 $version ist nicht installiert (asdf install $1 $version)" >&2; exit 1; }
  case "$dir" in
    "$installs"/*) ;;
    *) echo "$1: $dir liegt nicht unter $installs" >&2; exit 1 ;;
  esac
  printf '%s' "$dir"
}

ex=$(runtime elixir)
erl=$(runtime erlang)
[ -x "$ex/bin/elixir" ] && [ -x "$erl/bin/erl" ] \
  || { echo "Laufzeit unvollständig: $ex, $erl" >&2; exit 1; }

if [ -d "$dest" ]; then chmod -R u+w "$dest" && rm -rf "$dest"; fi
mkdir -p "$dest/bin" "$dest/scripts" "$dest/apps/seatbelt"
cp -R "$tmp/src/scripts/screenshot.exs" "$tmp/src/scripts/screenshot" "$dest/scripts/"
cp -R "$tmp/src/apps/seatbelt/lib" "$dest/apps/seatbelt/"
# Worktrees of this repository only (see worktree!/1 in the tool).
git rev-parse --path-format=absolute --git-common-dir > "$dest/scripts/screenshot/repo"
echo "$sha" > "$dest/COMMIT"

# HOME and TMPDIR are fixed here as well: the tool derives its scratch,
# cache and read-ban paths from HOME, the allowed output places from TMPDIR,
# and a caller could prefix either one.
cat > "$dest/bin/komki-screenshot" <<EOF
#!/bin/sh
# Generated by make screenshot-install (#510) from $repo@$sha.
exec /usr/bin/env -i HOME="$HOME" TMPDIR=/tmp LANG=en_US.UTF-8 PATH="$ex/bin:$erl/bin:/usr/bin:/bin" "$ex/bin/elixir" "$dest/scripts/screenshot.exs" "\$@"
EOF
chmod 755 "$dest/bin/komki-screenshot"
chmod -R a-w "$dest"

echo "Screenshot-Werkzeug installiert: $repo@$sha"
echo "Laufzeit: $ex, $erl"
echo "Starter: $dest/bin/komki-screenshot"
